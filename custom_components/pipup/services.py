def unsupported_position(position: str, app_version: str | None) -> str | None:
    """Return the minimum app version when this app cannot show the position yet.

    An unknown app version (TV not reached yet) is let through: the request then
    fails or succeeds on the TV as before.
    """
    return _needs_newer_app(POSITION_MIN_APP_VERSION.get(position), app_version)


def unsupported_media(payload: dict[str, Any], app_version: str | None) -> tuple[str, str] | None:
    """Return (media type, minimum app version) when this app cannot play the payload's media."""
    for kind in payload.get("media") or {}:
        if required := _needs_newer_app(MEDIA_MIN_APP_VERSION.get(kind), app_version):
            return kind, required
    return None


_VERSION_CORE = re.compile(r"^v?(\d+)\.(\d+)\.(\d+)")


def _needs_newer_app(required: str | None, app_version: str | None) -> str | None:
    """Return `required` when `app_version` is older; None when fine or unknown.

    Only the numeric x.y.z core counts: a build such as "0.25.0-rc1" or "0.25.0-debug"
    has the 0.25.0 features, while AwesomeVersion would rank it below 0.25.0.
    """
    if required is None or not app_version:
        return None
    have, need = _VERSION_CORE.match(app_version.strip()), _VERSION_CORE.match(required)
    if have and need:
        return required if tuple(map(int, have.groups())) < tuple(map(int, need.groups())) else None
    try:
        return required if AwesomeVersion(app_version) < AwesomeVersion(required) else None
    except AwesomeVersionException:
        return None


async def _coordinators_for_call(hass: HomeAssistant, call: ServiceCall) -> list:
    """Resolve targeted devices to loaded PiPup coordinators."""
    entry_ids = await async_extract_config_entry_ids(call)
    coordinators = []
    for entry_id in entry_ids:
        entry = hass.config_entries.async_get_entry(entry_id)
        if (
            entry is not None
            and entry.domain == DOMAIN
            and entry.state is ConfigEntryState.LOADED
        ):
            coordinators.append(entry.runtime_data)
    if not coordinators:
        raise HomeAssistantError(
            "No loaded PiPup devices in the action target; "
            "target a PiPup device (device_id)."
        )
    return coordinators


def build_device_payload(
    data: dict[str, Any],
    opts: dict[str, Any],
    stream_uri: str | None,
    web_uri: str | None = None,
    callback_url: str | None = None,
    poster_uri: str | None = None,
) -> dict[str, Any]:
    """Build the notify payload for one device.

    Every field falls back to the device's configured default (options
    flow) when not given in the action call.
    """

    def pick(attr: str, conf: str, fallback: Any) -> Any:
        if attr in data:
            return data[attr]
        value = opts.get(conf)
        # 0 / "" mean "not configured" for sizes and colors
        return value if value not in (None, 0, 0.0, "") else fallback

    def pick_numeric(attr: str, conf: str) -> Any:
        """Like pick(), but for fields where 0 is a real value.

        borderWidth 0 = no border (also switches an urgency border off) and
        cornerRadius 0 = square corners, so only a genuinely absent value may
        fall through to the app's own default.
        """
        if attr in data:
            return data[attr]
        return opts.get(conf)

    # Duration is special: 0 is a meaningful value (show indefinitely), so only
    # an absent default falls back — unlike sizes/colors where 0/"" mean "unset".
    duration_default = opts.get(CONF_DEFAULT_DURATION)
    payload: dict[str, Any] = {
        "duration": (
            data[ATTR_DURATION]
            if ATTR_DURATION in data
            else duration_default
            if duration_default is not None
            else 30
        ),
        "position": POSITIONS[
            data.get(ATTR_POSITION)
            or opts.get(CONF_DEFAULT_POSITION, DEFAULT_POSITION)
        ],
    }
    if popup_id := data.get(ATTR_POPUP_ID):
        payload["id"] = popup_id
    # app >= 0.29.1 (older ones ignore it): a window over the whole display, bars included
    if data.get(ATTR_FULLSCREEN):
        payload["fullscreen"] = True
    if title := data.get(ATTR_TITLE):
        payload["title"] = title
    if message := data.get(ATTR_MESSAGE):
        payload["message"] = message
    # app >= 0.19.0: compact buttons and animations; per-call value first, then the
    # per-device default. "none" suppresses a default animation for one call.
    if (button_size := pick(ATTR_BUTTON_SIZE, CONF_DEFAULT_BUTTON_SIZE, None)):
        payload["buttonSize"] = button_size
    # app >= 0.28.0 (older ones ignore it): button style; each part is sent only when set
    for attr, key in (
        (ATTR_BUTTON_COLOR, "buttonColor"),
        (ATTR_BUTTON_FOCUS_COLOR, "buttonFocusColor"),
        (ATTR_BUTTON_TEXT_COLOR, "buttonTextColor"),
        (ATTR_BUTTON_BORDER_COLOR, "buttonBorderColor"),
    ):
        if color := data.get(attr):
            payload[key] = color
    if (radius := data.get(ATTR_BUTTON_CORNER_RADIUS)) is not None:
        payload["buttonCornerRadius"] = radius
    if (padding := data.get(ATTR_PADDING)) is not None:
        payload["padding"] = padding
    # app >= 0.24.0: whole-popup alpha; an older app ignores it
    if (opacity := data.get(ATTR_OPACITY)) is not None:
        payload["opacity"] = opacity
    # app >= 0.24.0: a redraw opens on top of the other popups
    if data.get(ATTR_BRING_TO_FRONT):
        payload["bringToFront"] = True
    # app >= 0.28.0 (older ones ignore it): a LIVE pill over the stream once it plays
    if data.get(ATTR_LIVE_BADGE):
        payload["liveBadge"] = True
        if color := data.get(ATTR_LIVE_BADGE_COLOR):
            payload["liveBadgeColor"] = color
        if position := data.get(ATTR_LIVE_BADGE_POSITION):
            payload["liveBadgePosition"] = position
    # app >= 0.28.0 (older ones ignore it): media edge to edge, text and buttons padded
    if data.get(ATTR_MEDIA_FULL_BLEED):
        payload["mediaFullBleed"] = True
    # app >= 0.28.0: buttons at the end of the title/message row instead of below it
    if data.get(ATTR_BUTTONS_INLINE):
        payload["buttonsInline"] = True
    animation = data.get(ATTR_ANIMATION)
    if animation is None:
        animation = opts.get(CONF_DEFAULT_ANIMATION)
    if animation and animation != "none":
        payload["animation"] = animation
    # app >= 0.27.0: stack along the edge with the other popups at that position (#64);
    # per-call value first, then the per-device default. An older app ignores the field,
    # so popups just overlap there as before - no version gate needed.
    stack = data.get(ATTR_STACK)
    if stack is None:
        stack = opts.get(CONF_DEFAULT_STACK)
    if stack and stack != "none":
        payload["stack"] = stack

    # app >= 0.18.0: notification sound. "default" = built-in chime, else a URL. Per-call
    # value first, then the per-device default; an explicit empty string in the call means
    # "no sound this time" even when a default is set.
    sound = data.get(ATTR_SOUND)
    if sound is None:
        sound = opts.get(CONF_DEFAULT_SOUND) or None
    if sound:
        payload["sound"] = sound
        if (volume := data.get(ATTR_SOUND_VOLUME)) is not None:
            payload["soundVolume"] = volume
    # app >= 0.18.0: the app ends an active screensaver by default; only send the field when
    # someone asked to keep it (older apps ignore unknown fields either way).
    dismiss = data.get(ATTR_DISMISS_SCREENSAVER)
    if dismiss is None:
        dismiss = opts.get(CONF_DEFAULT_DISMISS_SCREENSAVER, True)
    if dismiss is False:
        payload["dismissScreensaver"] = False

    if tts := data.get(ATTR_TTS):
        payload["tts"] = tts  # spoken on the device (app >= 0.2.5)
        if language := data.get(ATTR_TTS_LANGUAGE):
            payload["ttsLanguage"] = language

    # app >= 0.3.0
    if urgency := data.get(ATTR_URGENCY):
        payload["urgency"] = urgency
    if data.get(ATTR_SHOW_PROGRESS):
        payload["showProgress"] = True
    if buttons := data.get(ATTR_BUTTONS):
        payload["buttons"] = buttons
        if callback_url:
            payload["callback"] = callback_url

    # app >= 0.7.0: explicit border styling. Each field overrides its part of the
    # urgency preset, so the two can be combined (critical + thin border, or
    # border_width 0 to keep the preset's semantics without its frame).
    if color := pick(ATTR_BORDER_COLOR, CONF_DEFAULT_BORDER_COLOR, None):
        payload["borderColor"] = color
    if (width_px := pick_numeric(ATTR_BORDER_WIDTH, CONF_DEFAULT_BORDER_WIDTH)) is not None:
        payload["borderWidth"] = width_px
    if (radius := pick_numeric(ATTR_CORNER_RADIUS, CONF_DEFAULT_CORNER_RADIUS)) is not None:
        payload["cornerRadius"] = radius

    # app >= 0.13.0: an icon beside the title/message. The URL is per-call (content);
    # position and width fall back to the device defaults like the styling fields.
    if icon := data.get(ATTR_ICON):
        payload["icon"] = icon
        payload["iconPosition"] = (
            data.get(ATTR_ICON_POSITION)
            or opts.get(CONF_DEFAULT_ICON_POSITION)
            or DEFAULT_ICON_POSITION
        )
        if (icon_width := pick(ATTR_ICON_WIDTH, CONF_DEFAULT_ICON_WIDTH, None)) is not None:
            payload["iconWidth"] = icon_width

    if color := pick(ATTR_TITLE_COLOR, CONF_DEFAULT_TITLE_COLOR, None):
        payload["titleColor"] = color
    if size := pick(ATTR_TITLE_SIZE, CONF_DEFAULT_TITLE_SIZE, None):
        payload["titleSize"] = size
    if color := pick(ATTR_MESSAGE_COLOR, CONF_DEFAULT_MESSAGE_COLOR, None):
        payload["messageColor"] = color
    if size := pick(ATTR_MESSAGE_SIZE, CONF_DEFAULT_MESSAGE_SIZE, None):
        payload["messageSize"] = size
    if color := pick(ATTR_BACKGROUND_COLOR, CONF_DEFAULT_BACKGROUND_COLOR, None):
        payload["backgroundColor"] = color

    width = pick(ATTR_MEDIA_WIDTH, CONF_DEFAULT_MEDIA_WIDTH, 640)
    height = pick(ATTR_MEDIA_HEIGHT, CONF_DEFAULT_MEDIA_HEIGHT, 360)
    muted = data.get(ATTR_MUTED, opts.get(CONF_DEFAULT_MUTED, True))

    # app >= 0.28.0 (older ones ignore it): an explicit per-call media_height fixes a video popup's box until the
    # stream reports its display aspect, so an anamorphic camera snapshot (an NVR's 704x480
    # still of a 4:3 picture) shows at the right shape. Only a per-call value is sent: the
    # per-device default would change every existing video popup's poster sizing.
    video_height = data.get(ATTR_MEDIA_HEIGHT)

    if stream_uri:
        payload["media"] = {"video": {"uri": stream_uri, "width": width, "muted": muted}}
        if video_height:
            payload["media"]["video"]["height"] = video_height
    elif web_uri:
        payload["media"] = {
            "web": {"uri": web_uri, "width": width, "height": height, "muted": muted}
        }
    elif url := data.get(ATTR_WEB_URL):
        payload["media"] = {
            "web": {"uri": url, "width": width, "height": height, "muted": muted}
        }
        # app >= 0.24.0: no WebView background, so a page with a
        # transparent body shows the TV behind it
        if data.get(ATTR_TRANSPARENT):
            payload["media"]["web"]["transparent"] = True
    elif tiles := data.get(ATTR_GRID):
        # app >= 0.29.0: a camera wall, one WHEP stream per tile; media_width/height size
        # the whole grid, grid_fullscreen fills the screen
        grid: dict[str, Any] = {
            "items": tiles,
            "width": data.get(ATTR_MEDIA_WIDTH) or 1280,
            "height": data.get(ATTR_MEDIA_HEIGHT) or 720,
            "muted": muted,
        }
        if (columns := data.get(ATTR_GRID_COLUMNS)) is not None:
            grid["columns"] = columns
        if data.get(ATTR_GRID_LABELS) is False:
            grid["labels"] = False
        if data.get(ATTR_GRID_FULLSCREEN):
            grid["fullscreen"] = True
            payload["fullscreen"] = True
            # a wall is meant edge to edge: centred and without the popup margin,
            # unless the call says otherwise
            if ATTR_POSITION not in data:
                payload["position"] = POSITIONS["center"]
            if ATTR_PADDING not in data:
                payload["padding"] = 0
        payload["media"] = {"grid": grid}
    elif url := data.get(ATTR_WHEP_URL):
        # app >= 0.25.0: the app negotiates WebRTC with the endpoint itself, without
        # loading the server's player page (go2rtc: http://host:1984/api/webrtc?src=<name>)
        payload["media"] = {
            "whep": {"uri": url, "width": width, "height": height, "muted": muted}
        }
        if data.get(ATTR_TRANSPARENT):
            payload["media"]["whep"]["transparent"] = True
    elif url := data.get(ATTR_VIDEO_URL):
        payload["media"] = {"video": {"uri": url, "width": width, "muted": muted}}
        if video_height:
            payload["media"]["video"]["height"] = video_height
    elif url := data.get(ATTR_IMAGE_URL):
        payload["media"] = {"image": {"uri": url, "width": width}}

    # app >= 0.31.0 (older ones ignore it, PiPup #79): a live video stream starts once this
    # much is buffered and stays that close to the camera, instead of ExoPlayer's 2.5 s
    if (buffer_ms := data.get(ATTR_BUFFER_MS)) and "video" in (payload.get("media") or {}):
        payload["media"]["video"]["bufferMs"] = buffer_ms

    # app >= 0.17.0: poster — a still shown over the stream area until the first frame
    # renders, so a live popup never opens as an empty box while the stream connects.
    # An explicit poster_url wins; a camera_entity popup gets its own snapshot for free.
    media = payload.get("media") or {}
    kind = next((k for k in ("video", "web", "whep") if k in media), None)
    if kind and (poster := data.get(ATTR_POSTER_URL) or poster_uri):
        media[kind]["poster"] = poster

    return payload


async def _camera_media(
    hass: HomeAssistant, data: dict[str, Any]
) -> tuple[str | None, str | None, bytes | None, str | None]:
    """Resolve a camera entity to (video_uri, web_uri, snapshot_bytes, poster_uri).

    Default is MJPEG via HA's camera proxy (rendered in the popup's web view,
    audio-free). 'stream' (HLS) plays through ExoPlayer in a TextureView (app
    >= 0.16.0), which renders over video the TV is already playing. For both
    live modes a signed still of the same camera is returned as poster: the
    app shows it instantly and fades it out on the stream's first frame.
    """
    # Imported here so the camera/stream components stay optional.
    from homeassistant.components.camera import (  # noqa: PLC0415
        async_get_image,
        async_request_stream,
    )

    entity_id = data[ATTR_CAMERA_ENTITY]
    mode = data.get(ATTR_CAMERA_MODE, CAMERA_MODE_MJPEG)
    base_url = get_url(hass, allow_external=False, prefer_external=False)

    if mode == CAMERA_MODE_SNAPSHOT:
        image = await async_get_image(hass, entity_id)
        return None, None, image.content, None

    from datetime import timedelta  # noqa: PLC0415

    from homeassistant.components.http.auth import (  # noqa: PLC0415
        async_sign_path,
    )

    # Poster: fetched once, right when the popup opens - a short signature is plenty.
    poster = base_url + async_sign_path(
        hass, f"/api/camera_proxy/{entity_id}", timedelta(hours=1)
    )

    if mode == CAMERA_MODE_MJPEG:
        # An indefinite popup (duration <= 0) keeps the same signed URL open for
        # as long as it is shown, so a 24 h signature would make the stream go
        # 401 after a day. The call's duration is not the whole story: a missing
        # duration falls back to the PER-DEVICE default, which since 1.7.0 may
        # itself be 0 (indefinite) - and this helper cannot know which TV it is
        # signing for. So only an explicit, finite duration gets the short
        # signature; everything else gets the long one (a longer signature on a
        # short popup costs nothing).
        duration = data.get(ATTR_DURATION)
        expiry = (
            timedelta(hours=24)
            if duration is not None and duration > 0
            else timedelta(days=30)
        )
        signed = async_sign_path(
            hass,
            f"/api/camera_proxy_stream/{entity_id}",
            expiry,
        )
        return None, f"{base_url}{signed}", None, poster

    stream_path = await async_request_stream(hass, entity_id, "hls")
    return f"{base_url}{stream_path}", None, None, poster


def _issue_button_token(
    hass: HomeAssistant,
    popup_id: str | None,
    buttons: list[dict[str, Any]] | None = None,
    coordinator: Any = None,
) -> str:
    """Mint a single-use token for a button popup and remember it.

    The token travels in the callback URL and must come back on the button
    press, so a device on the LAN cannot forge a pipup_button event by POSTing
    a guessed device id — which matters when button events drive things like a
    door lock. Expired tokens are swept on each issue.

    The token is bound to what was shown: the popup id, the buttons on it and the
    TV it went to. The event is built from that, not from the callback body, so a
    token holder cannot turn one popup's token into another popup's (or TV's) press.
    """
    tokens: dict[str, dict[str, Any]] = hass.data.setdefault(DOMAIN, {}).setdefault(
        DATA_BUTTON_TOKENS, {}
    )
    now = dt_util.utcnow()
    for tok in [t for t, meta in tokens.items() if meta["expires"] < now]:
        tokens.pop(tok, None)
    device_id: str | None = None
    device_name: str | None = None
    if coordinator is not None:
        state = coordinator.data or {}
        entry = coordinator.config_entry
        # the app's stable id and name, as the app itself puts them in the callback
        device_id = state.get("id") or entry.unique_id
        device_name = state.get("name")
    token = secrets.token_urlsafe(24)
    tokens[token] = {
        "popup_id": popup_id,
        "buttons": [
            {"id": b.get("id"), "label": b.get("label")} for b in buttons or []
        ],
        "device_id": device_id,
        "device_name": device_name,
        "expires": now + BUTTON_TOKEN_TTL,
    }
    return token


async def _handle_button_webhook(hass: HomeAssistant, webhook_id: str, request) -> None:
    """Fire a pipup_button event for a button press POSTed by the app.

    The press is only honored when it carries a valid, unexpired, single-use
    token that this integration handed out when it showed the popup.
    """
    token = request.query.get("token")
    tokens: dict[str, dict[str, Any]] = hass.data.get(DOMAIN, {}).get(
        DATA_BUTTON_TOKENS, {}
    )
    meta = tokens.pop(token, None) if token else None
    if meta is None or meta["expires"] < dt_util.utcnow():
        _LOGGER.warning(
            "Rejecting PiPup button callback with missing/invalid/expired token"
        )
        return

    try:
        data = await request.json()
    except ValueError:
        _LOGGER.warning("Invalid JSON on %s webhook", webhook_id)
        return
    _LOGGER.debug("Popup button pressed: %s", data)
    if not isinstance(data, dict):
        _LOGGER.warning("Invalid payload on %s webhook", webhook_id)
        return
    # Only a button that was on the popup this token was issued for counts; popup,
    # label and TV come from what HA showed, never from the request body.
    button = data.get("button")
    issued = next((b for b in meta.get("buttons") or [] if b["id"] == button), None)
    if issued is None:
        _LOGGER.warning(
            "Rejecting PiPup button callback: button %r was not on popup %r",
            button, meta.get("popup_id"),
        )
        return
    hass.bus.async_fire(
        EVENT_BUTTON,
        {
            "popup_id": meta.get("popup_id"),
            "button": issued["id"],
            "label": issued["label"],
            "device_id": meta.get("device_id"),
            "device_name": meta.get("device_name"),
        },
    )


async def _refresh_unless_pushed(coordinator) -> None:
    """Read /state after a call, unless the app pushes the change itself.

    An app with push (>= 0.24.0) posts popup_shown/popup_removed on its own, so the
    extra settle delay plus /state round-trip only slowed the action down.
    """
    if not coordinator.push_active:
        await coordinator.async_refresh_soon()


def _raise_errors(results: list[Any]) -> None:
    """Raise the per-TV errors of a gathered call, in target order, as one message."""
    errors: list[str] = []
    for result in results:
        if isinstance(result, BaseException):
            raise result  # not a TV error: surface it as before
        if result:
            errors.append(result)
    if errors:
        raise HomeAssistantError("; ".join(errors))


async def async_setup_services(hass: HomeAssistant) -> None:
    """Register the pipup.show/pipup.dismiss actions and the button webhook."""

    try:
        webhook_component.async_register(
            hass,
            DOMAIN,
            "PiPup buttons",
            WEBHOOK_ID,
            _handle_button_webhook,
            local_only=True,
            allowed_methods=["POST"],
        )
    except ValueError:
        _LOGGER.debug("Webhook %s already registered", WEBHOOK_ID)

    async def handle_show(call: ServiceCall) -> None:
        coordinators = await _coordinators_for_call(hass, call)
        data = call.data

        stream_uri: str | None = None
        web_uri: str | None = None
        poster_uri: str | None = None
        snapshot: bytes | None = None
        if data.get(ATTR_CAMERA_ENTITY):
            stream_uri, web_uri, snapshot, poster_uri = await _camera_media(hass, data)

        # Buttons can't ride along in the multipart/snapshot request, so warn
        # instead of silently dropping them (the app's multipart parser has no
        # buttons/urgency/showProgress field).
        if data.get(ATTR_BUTTONS) and snapshot is not None:
            _LOGGER.warning(
                "PiPup: buttons are ignored when camera_mode is 'snapshot' "
                "(multipart upload). Use mjpeg/stream or an image_url for buttons."
            )

        want_buttons = bool(data.get(ATTR_BUTTONS)) and snapshot is None
        base_url = (
            get_url(hass, allow_external=False, prefer_external=False)
            if want_buttons
            else None
        )

        async def _show_on(coordinator) -> str | None:
            """Show the popup on one TV; the error text, or None when it worked."""
            opts = dict(coordinator.config_entry.options)
            # A fresh single-use token per device: the button press must return
            # it in the callback URL for the pipup_button event to fire.
            callback_url: str | None = None
            if want_buttons:
                token = _issue_button_token(
                    hass, data.get(ATTR_POPUP_ID), data.get(ATTR_BUTTONS), coordinator
                )
                callback_url = f"{base_url}/api/webhook/{WEBHOOK_ID}?token={token}"
            position = data.get(ATTR_POSITION) or opts.get(CONF_DEFAULT_POSITION, DEFAULT_POSITION)
            app_version = (coordinator.data or {}).get("version")
            if required := unsupported_position(position, app_version):
                return (
                    f"{coordinator.config_entry.title}: position '{position}' needs "
                    f"PiPup app {required} or newer (this TV runs {app_version})"
                )
            payload = build_device_payload(data, opts, stream_uri, web_uri, callback_url, poster_uri)
            if unsupported := unsupported_media(payload, app_version):
                return (
                    f"{coordinator.config_entry.title}: "
                    f"{unsupported[0] if unsupported[0] == 'grid' else unsupported[0] + '_url'} needs "
                    f"PiPup app {unsupported[1]} or newer (this TV runs {app_version})"
                )
            try:
                if snapshot is not None:
                    fields = {
                        key: str(value)
                        for key, value in payload.items()
                        if key != "media"
                    }
                    fields["imageWidth"] = str(
                        payload.get("media", {}).get("image", {}).get("width")
                        or data.get(ATTR_MEDIA_WIDTH)
                        or opts.get(CONF_DEFAULT_MEDIA_WIDTH)
                        or 640
                    )
                    await coordinator.client.notify_image(fields, snapshot)
                else:
                    await coordinator.client.notify(payload)
                await _refresh_unless_pushed(coordinator)
            except PiPupError as err:
                return str(err)
            return None

        # every TV at once: one slow or unreachable TV no longer holds up the others
        _raise_errors(
            await asyncio.gather(
                *(_show_on(c) for c in coordinators), return_exceptions=True
            )
        )

    async def handle_dismiss(call: ServiceCall) -> None:
        coordinators = await _coordinators_for_call(hass, call)
        popup_id = call.data.get(ATTR_POPUP_ID)
        all_popups = call.data.get(ATTR_ALL, False)

        async def _dismiss_on(coordinator) -> str | None:
            try:
                await coordinator.client.cancel(popup_id, all_popups=all_popups)
                await _refresh_unless_pushed(coordinator)
            except PiPupError as err:
                return str(err)
            return None

        _raise_errors(
            await asyncio.gather(
                *(_dismiss_on(c) for c in coordinators), return_exceptions=True
            )
        )

    def _control_unsupported(coordinator) -> str | None:
        """Why this TV cannot take TV-control calls, or None."""
        data = coordinator.data or {}
        if isinstance(data.get("control"), dict):
            return None
        version = data.get("version")
        if version and not _needs_newer_app(CONTROL_MIN_APP_VERSION, version):
            return None  # new enough; /state just not read since the update
        return (
            f"{coordinator.config_entry.title}: TV control needs PiPup app "
            f"{CONTROL_MIN_APP_VERSION} or newer (this TV runs {version or 'unknown'})"
        )

    def _app_too_old(coordinator, required: str, what: str) -> str | None:
        """Why this TV's app is too old for `what`, or None (also when unknown)."""
        version = (coordinator.data or {}).get("version")
        if _needs_newer_app(required, version):
            return (
                f"{coordinator.config_entry.title}: {what} needs PiPup app "
                f"{required} or newer (this TV runs {version})"
            )
        return None

    async def _press_ok_over_adb(coordinator, answer: Any) -> Any:
        """method=ok below Android 13: the app focused the view, ADB presses OK.

        App >= 0.32.0-beta.3 answers `pressed: false, key: KEYCODE_DPAD_CENTER` when it
        cannot press OK itself (Android < 13). Only that one fixed key is sent, and only
        to a TV with a tested ADB setup.
        """
        if not (
            isinstance(answer, dict)
            and answer.get("method") == CLICK_METHOD_OK
            and answer.get("focused") is True
            and answer.get("pressed") is False
            and answer.get("key") == KEYCODE_DPAD_CENTER
        ):
            return answer
        options = coordinator.config_entry.options
        if not adb_ready(options, coordinator.data or {}):
            raise PiPupError(
                "the view has the focus, but before Android 13 only ADB can press OK. "
                "Set up ADB under Advanced install in this TV's options"
            )
        try:
            await async_adb_key(hass, coordinator.client.host, options, KEYCODE_DPAD_CENTER)
        except AdbError as err:
            raise PiPupError(f"the view has the focus, but pressing OK over ADB failed: {err}") from err
        # `changed` is the app's to measure, and it answered before the press
        return {**answer, "pressed": True, "pressed_over_adb": True, "changed": None}

    async def _control_on_all(
        call: ServiceCall,
        action,
        needs: tuple[str, str] | None = None,
        wake: bool = False,
        after=None,
    ) -> dict[str, Any]:
        """Run a TV-control call on every targeted TV; `needs` = (app version, what).

        `wake`: wake a TV whose screen is off first (the app, then ADB; 1.32.0b3), so
        an app is not opened on a dark screen. `after(coordinator, answer)` may finish
        the job (press OK over ADB) and returns the answer to report.
        Returns the app's answer per TV (by entry title), for actions that respond.
        """
        coordinators = await _coordinators_for_call(hass, call)
        answers: dict[str, Any] = {}

        async def _one(coordinator) -> str | None:
            if reason := _control_unsupported(coordinator):
                return reason
            if needs and (reason := _app_too_old(coordinator, *needs)):
                return reason
            try:
                if wake and (coordinator.data or {}).get("screenOn") is False:
                    await coordinator.async_screen_on()
                answer = await action(coordinator.client)
                if after is not None:
                    answer = await after(coordinator, answer)
                answers[coordinator.config_entry.title] = answer if isinstance(answer, dict) else {}
                await _refresh_unless_pushed(coordinator)
            except PiPupError as err:
                return f"{coordinator.config_entry.title}: {err}"
            return None

        _raise_errors(
            await asyncio.gather(*(_one(c) for c in coordinators), return_exceptions=True)
        )
        return answers

    async def handle_launch_app(call: ServiceCall) -> ServiceResponse:
        package = call.data.get(ATTR_PACKAGE)
        uri = call.data.get(ATTR_URI)
        click = call.data.get(ATTR_CLICK)
        if not package and not uri:
            raise HomeAssistantError("launch_app needs a package and/or a uri")
        kwargs: dict[str, Any] = {"package": package, "uri": uri, "wake": call.data[ATTR_WAKE]}
        if click:
            # app >= 0.32.0 only; left out otherwise, so older apps get the old call
            kwargs["click"] = click
            kwargs["wait"] = call.data.get(ATTR_WAIT)
            if method := call.data.get(ATTR_METHOD):
                kwargs["method"] = method
        answers = await _control_on_all(
            call,
            lambda client: client.launch(**kwargs),
            needs=(MEDIA_CLICK_MIN_APP_VERSION, "launch_app with click") if click else None,
            wake=call.data[ATTR_WAKE],
            after=_press_ok_over_adb if click else None,
        )
        # the app's answer per TV: launched, clicked, and since 0.32.0-beta.2 method + changed
        return {"tvs": answers} if call.return_response else None

    async def handle_click(call: ServiceCall) -> ServiceResponse:
        """Press a view in an app on the TV's allowed list (app >= 0.32.0)."""
        answers = await _control_on_all(
            call,
            lambda client: client.click(
                call.data[ATTR_PACKAGE], call.data[ATTR_ID], call.data[ATTR_WAIT],
                method=call.data.get(ATTR_METHOD),
            ),
            needs=(MEDIA_CLICK_MIN_APP_VERSION, "click"),
            after=_press_ok_over_adb,
        )
        # per TV: ok, message, and since app 0.32.0-beta.2 method + changed (did the screen react)
        return {"tvs": answers} if call.return_response else None

    async def handle_seek(call: ServiceCall) -> None:
        """Seek the media session to a position, or by an offset (app >= 0.32.0)."""
        position = call.data.get(ATTR_SEEK_POSITION)
        offset = call.data.get(ATTR_SEEK_OFFSET)
        if position is None and offset is None:
            raise HomeAssistantError("seek needs a position or an offset (seconds)")
        package = call.data.get(ATTR_PACKAGE)
        if position is not None:
            action = lambda client: client.seek(ms=round(position * 1000), package=package)  # noqa: E731
        else:
            action = lambda client: client.seek(by=round(offset * 1000), package=package)  # noqa: E731
        await _control_on_all(call, action, needs=(MEDIA_CLICK_MIN_APP_VERSION, "seek"))

    async def handle_send_key(call: ServiceCall) -> None:
        key = call.data[ATTR_KEY]
        await _control_on_all(call, lambda client: client.key(key))

    async def handle_sync(call: ServiceCall) -> None:
        """Read /state now on the targeted TV(s) and re-send the push webhook."""
        coordinators = await _coordinators_for_call(hass, call)
        offline: list[str] = []
        for coordinator in coordinators:
            await coordinator.async_sync()
            if not coordinator.online:
                offline.append(coordinator.client.host)
        if offline:
            raise HomeAssistantError(f"did not answer: {', '.join(offline)}")

    async def handle_fix_permission(call: ServiceCall) -> None:
        """Put a permission screen on the TV(s) in the target.

        Errors are collected rather than raised per device: with several TVs targeted,
        the ones that *can* show a screen should still do so, and the message names the
        ones that need adb (the app returns the exact command).
        """
        coordinators = await _coordinators_for_call(hass, call)
        what = call.data.get(ATTR_PERMISSION, "app")

        errors: list[str] = []
        for coordinator in coordinators:
            try:
                await coordinator.client.fix_permission(None if what == "app" else what)
            except (PiPupError, PiPupUnsupportedError) as err:
                errors.append(f"{coordinator.client.host}: {err}")

        if errors:
            raise HomeAssistantError("; ".join(errors))

    hass.services.async_register(
        DOMAIN, SERVICE_SHOW, handle_show, schema=SHOW_SCHEMA
    )
    hass.services.async_register(
        DOMAIN,
        SERVICE_FIX_PERMISSION,
        handle_fix_permission,
        schema=FIX_PERMISSION_SCHEMA,
    )
    hass.services.async_register(
        DOMAIN, SERVICE_DISMISS, handle_dismiss, schema=DISMISS_SCHEMA
    )
    hass.services.async_register(
        DOMAIN, SERVICE_SYNC, handle_sync, schema=vol.Schema({}, extra=vol.ALLOW_EXTRA)
    )
    hass.services.async_register(
        DOMAIN, SERVICE_LAUNCH_APP, handle_launch_app, schema=LAUNCH_APP_SCHEMA,
        supports_response=SupportsResponse.OPTIONAL,
    )
    hass.services.async_register(
        DOMAIN, SERVICE_SEND_KEY, handle_send_key, schema=SEND_KEY_SCHEMA
    )
    hass.services.async_register(
        DOMAIN, SERVICE_CLICK, handle_click, schema=CLICK_SCHEMA,
        supports_response=SupportsResponse.OPTIONAL,
    )
    hass.services.async_register(
        DOMAIN, SERVICE_SEEK, handle_seek, schema=SEEK_SCHEMA
    )
