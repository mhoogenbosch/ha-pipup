"""Thin async client for the PiPup HTTP API (fork with /state support).

Generated by aurora@aurora-smart-home (ha-integration-dev skill)
https://github.com/tonylofgren/aurora-smart-home
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import aiohttp

# Announced on every request (X-HA-PiPup-Version). The app (>= 0.21.0) remembers the
# last value it saw and shows it on its status screen and in /state next to the
# recommended (= latest released) integration version. Read from the manifest so it
# can never drift from the actual release.
_VERSION: str = json.loads(
    (Path(__file__).parent / "manifest.json").read_text(encoding="utf-8")
)["version"]
_HEADERS: dict[str, str] = {"X-HA-PiPup-Version": _VERSION}
# Whether Home Assistant installs the app's updates by itself (automatic updates on, and
# able to install on this TV). The app (>= 0.30.1) then skips its own "update available"
# popup, whose Install button took the remote's focus mid-film (PiPup #76).
AUTO_UPDATE_HEADER = "X-HA-PiPup-Auto-Update"


class PiPupError(Exception):
    """Communication error with the PiPup device."""


class PiPupUnsupportedError(PiPupError):
    """Device responds but does not support the fork API (/state)."""


class PiPupClient:
    """Async client for a single PiPup device."""

    def __init__(self, session: aiohttp.ClientSession, host: str, port: int) -> None:
        """Initialize the client."""
        self._session = session
        self._base = f"http://{host}:{port}"
        self.host = host
        self.port = port
        # set by the coordinator after each /state; None until then (header left out)
        self.auto_update: bool | None = None

    @property
    def _headers(self) -> dict[str, str]:
        """Headers for every request: the version, and the automatic-update flag once known."""
        if self.auto_update is None:
            return _HEADERS
        return {**_HEADERS, AUTO_UPDATE_HEADER: "on" if self.auto_update else "off"}

    async def state(self) -> dict[str, Any]:
        """Fetch /state from the device."""
        try:
            async with self._session.get(
                f"{self._base}/state", headers=self._headers,
                timeout=aiohttp.ClientTimeout(total=10)
            ) as resp:
                if resp.status == 400:
                    # Upstream PiPup without the fork additions answers
                    # "invalid request" on unknown URIs/methods.
                    raise PiPupUnsupportedError(
                        "PiPup fork with /state support required"
                    )
                resp.raise_for_status()
                return await resp.json(content_type=None)
        except PiPupError:
            raise
        except (aiohttp.ClientError, TimeoutError) as err:
            raise PiPupError(f"Cannot reach PiPup at {self._base}: {err}") from err

    async def notify(self, payload: dict[str, Any]) -> None:
        """Show a popup."""
        try:
            async with self._session.post(
                f"{self._base}/notify",
                json=payload,
                headers=self._headers,
                timeout=aiohttp.ClientTimeout(total=10),
            ) as resp:
                if resp.status != 200:
                    body = await resp.text()
                    raise PiPupError(f"notify failed ({resp.status}): {body}")
        except PiPupError:
            raise
        except (aiohttp.ClientError, TimeoutError) as err:
            raise PiPupError(f"Cannot reach PiPup at {self._base}: {err}") from err

    async def notify_image(self, fields: dict[str, str], image: bytes) -> None:
        """Show a popup with an uploaded snapshot image (multipart)."""
        form = aiohttp.FormData()
        for key, value in fields.items():
            form.add_field(key, value)
        form.add_field(
            "image", image, filename="snapshot.jpg", content_type="image/jpeg"
        )
        try:
            async with self._session.post(
                f"{self._base}/notify",
                data=form,
                headers=self._headers,
                timeout=aiohttp.ClientTimeout(total=15),
            ) as resp:
                if resp.status != 200:
                    body = await resp.text()
                    raise PiPupError(f"notify failed ({resp.status}): {body}")
        except PiPupError:
            raise
        except (aiohttp.ClientError, TimeoutError) as err:
            raise PiPupError(f"Cannot reach PiPup at {self._base}: {err}") from err

    async def update_app(self) -> None:
        """Ask the app to download and install the latest release (app >= 0.6.0).

        Returns as soon as the device accepted the request: the install itself
        runs on the TV and its progress shows up in /state.
        """
        try:
            async with self._session.post(
                f"{self._base}/update", headers=self._headers,
                timeout=aiohttp.ClientTimeout(total=15)
            ) as resp:
                if resp.status == 400:
                    raise PiPupUnsupportedError(
                        "this PiPup version has no self-update (needs app >= 0.6.0)"
                    )
                if resp.status != 200:
                    body = await resp.text()
                    raise PiPupError(f"update failed ({resp.status}): {body}")
        except PiPupError:
            raise
        except (aiohttp.ClientError, TimeoutError) as err:
            raise PiPupError(f"Cannot reach PiPup at {self._base}: {err}") from err

    async def power(self, state: str) -> dict[str, Any]:
        """Turn the device's screen on or off (app >= 0.7.0).

        The app answers 501 when it has no granted way to turn the screen off
        (no device admin, no accessibility service) and 400 when it predates
        /power entirely - both surface as PiPupUnsupportedError, so the caller
        can tell "this device cannot" apart from a network failure.
        """
        try:
            async with self._session.post(
                f"{self._base}/power",
                params={"state": state},
                headers=self._headers,
                timeout=aiohttp.ClientTimeout(total=10),
            ) as resp:
                if resp.status in (400, 501):
                    body = await resp.text()
                    raise PiPupUnsupportedError(
                        f"device cannot switch its screen {state}: {body}"
                    )
                if resp.status != 200:
                    body = await resp.text()
                    raise PiPupError(f"power failed ({resp.status}): {body}")
                return await resp.json(content_type=None)
        except PiPupError:
            raise
        except (aiohttp.ClientError, TimeoutError) as err:
            raise PiPupError(f"Cannot reach PiPup at {self._base}: {err}") from err

    async def fix_permission(self, what: str | None = None) -> dict[str, Any]:
        """Ask the TV to put a permission screen in front of the user (app >= 0.8.0).

        `what` picks a specific permission, "next" the first missing one; omitted opens
        PiPup's own status screen, which lists them all with their own buttons. The app
        answers 501 when this device has no such screen - Fire OS resolves those intents
        to do-nothing placeholders - and its reply then carries the adb command instead.
        """
        params = {"what": what} if what else None
        try:
            async with self._session.post(
                f"{self._base}/permissions/fix",
                params=params,
                headers=self._headers,
                timeout=aiohttp.ClientTimeout(total=15),
            ) as resp:
                if resp.status in (400, 501):
                    body = await resp.json(content_type=None)
                    # The app explains itself (app >= 0.9.0 sends `reason`, e.g. that
                    # Android blocks a background activity start without the overlay
                    # permission); pass that through rather than a generic failure, and
                    # append the adb command so the message is actionable on its own.
                    parts = [
                        part
                        for part in (body.get("reason"), body.get("adb"))
                        if part
                    ]
                    raise PiPupUnsupportedError(
                        " - ".join(parts)
                        or f"this device cannot open that screen ({resp.status})"
                    )
                if resp.status != 200:
                    body = await resp.text()
                    raise PiPupError(f"permission fix failed ({resp.status}): {body}")
                return await resp.json(content_type=None)
        except PiPupError:
            raise
        except (aiohttp.ClientError, TimeoutError) as err:
            raise PiPupError(f"Cannot reach PiPup at {self._base}: {err}") from err

    async def diagnose(self) -> dict[str, Any] | None:
        """Fetch /permissions/diagnose (app >= 0.9.0), or None on an older app.

        Rides along in the integration's diagnostics download so a bug report carries
        the per-permission facts - which activity resolves each settings screen, whether
        it is a vendor placeholder, whether a background launch is even allowed - instead
        of the reporter being asked for adb and a logcat.
        """
        try:
            async with self._session.get(
                f"{self._base}/permissions/diagnose",
                headers=self._headers,
                timeout=aiohttp.ClientTimeout(total=10),
            ) as resp:
                if resp.status != 200:
                    return None
                return await resp.json(content_type=None)
        except (aiohttp.ClientError, TimeoutError):
            return None

    async def cancel(self, popup_id: str | None = None, all_popups: bool = False) -> None:
        """Remove a popup: the one with popup_id, else the one without an id.

        App >= 0.24.0 keeps several popups up; all_popups removes
        every one. An older app shows one popup and ignores `all`.
        """
        if all_popups:
            params = {"all": "true"}
        else:
            params = {"id": popup_id} if popup_id else None
        try:
            async with self._session.post(
                f"{self._base}/cancel",
                params=params,
                headers=self._headers,
                timeout=aiohttp.ClientTimeout(total=10),
            ) as resp:
                if resp.status != 200:
                    body = await resp.text()
                    raise PiPupError(f"cancel failed ({resp.status}): {body}")
        except PiPupError:
            raise
        except (aiohttp.ClientError, TimeoutError) as err:
            raise PiPupError(f"Cannot reach PiPup at {self._base}: {err}") from err

    async def settings(self, **values: str) -> dict[str, Any]:
        """Read or change the app's persistent settings (app >= 0.24.0).

        With no values this is a plain read. Keys: ``webhook`` (push target, empty =
        off), ``updateSource`` and ``updateChecks``. An app without /settings answers
        400, raised as PiPupUnsupportedError.
        """
        try:
            async with self._session.post(
                f"{self._base}/settings",
                params=values or None,
                headers=self._headers,
                timeout=aiohttp.ClientTimeout(total=10),
            ) as resp:
                if resp.status == 400 and not values:
                    raise PiPupUnsupportedError("app has no /settings (needs >= 0.24.0)")
                if resp.status != 200:
                    body = await resp.text()
                    raise PiPupError(f"settings failed ({resp.status}): {body}")
                return await resp.json(content_type=None)
        except PiPupError:
            raise
        except (aiohttp.ClientError, TimeoutError) as err:
            raise PiPupError(f"Cannot reach PiPup at {self._base}: {err}") from err

    async def apps(self) -> list[dict[str, Any]]:
        """Launchable apps on the TV (app >= 0.29.0): package, label, tv."""
        try:
            async with self._session.get(
                f"{self._base}/apps",
                headers=self._headers,
                timeout=aiohttp.ClientTimeout(total=10),
            ) as resp:
                if resp.status == 400:
                    raise PiPupUnsupportedError("app has no /apps (needs >= 0.29.0)")
                if resp.status != 200:
                    body = await resp.text()
                    raise PiPupError(f"apps failed ({resp.status}): {body}")
                data = await resp.json(content_type=None)
                apps = data.get("apps") if isinstance(data, dict) else None
                return [a for a in apps or [] if isinstance(a, dict) and a.get("package")]
        except PiPupError:
            raise
        except (aiohttp.ClientError, TimeoutError) as err:
            raise PiPupError(f"Cannot reach PiPup at {self._base}: {err}") from err

    async def launch(
        self,
        package: str | None = None,
        uri: str | None = None,
        wake: bool = True,
        click: str | None = None,
        wait: int | None = None,
    ) -> dict[str, Any]:
        """Start an app or open a deep link (app >= 0.29.0).

        `click` (app >= 0.32.0) presses that view once the page is up, waiting up to
        `wait` seconds for it (the app's default is 10 when `click` is given).
        """
        params = {k: v for k, v in (("package", package), ("uri", uri)) if v}
        if not wake:
            params["wake"] = "false"
        if click:
            params["click"] = click
            if wait is not None:
                params["wait"] = str(wait)
        waits = (wait if wait is not None else 10) if click else 0
        return await self._control("/launch", params, timeout=10 + waits)

    async def click(self, package: str, view_id: str, wait: int = 0) -> dict[str, Any]:
        """Press a view in an app on the allowed list (app >= 0.32.0).

        The app answers 403 for an app that is not allowed, 404 when the view did not
        show up within `wait` seconds, and 501 when its control service is off.
        """
        params = {"package": package, "id": view_id}
        if wait:
            params["wait"] = str(wait)
        return await self._control("/click", params, timeout=10 + wait)

    async def media(self) -> dict[str, Any]:
        """The active media session (app >= 0.32.0); {"package": None} when idle.

        501 (media session access not granted, or a low-RAM device) and 400 (an app
        without /media) are raised as PiPupUnsupportedError.
        """
        try:
            async with self._session.get(
                f"{self._base}/media", headers=self._headers,
                timeout=aiohttp.ClientTimeout(total=10)
            ) as resp:
                text = await resp.text()
                try:
                    body = json.loads(text) if text else {}
                except ValueError:
                    body = {"message": text}
                if not isinstance(body, dict):
                    body = {"message": text}
                if resp.status == 200:
                    return body
                if resp.status == 400:
                    raise PiPupUnsupportedError("app has no /media (needs >= 0.32.0)")
                message = body.get("message") or text
                if resp.status == 501:
                    raise PiPupUnsupportedError(message)
                raise PiPupError(f"media failed ({resp.status}): {message}")
        except PiPupError:
            raise
        except (aiohttp.ClientError, TimeoutError) as err:
            raise PiPupError(f"Cannot reach PiPup at {self._base}: {err}") from err

    async def seek(
        self, ms: int | None = None, by: int | None = None, package: str | None = None
    ) -> dict[str, Any]:
        """Seek the media session (app >= 0.32.0): to `ms`, or `by` ± ms.

        Exactly one of the two. 404 = nothing playing, 409 = the app does not allow
        seeking, 501 = no media session access.
        """
        if (ms is None) == (by is None):
            raise ValueError("give exactly one of ms or by")
        params = {"ms": str(ms)} if ms is not None else {"by": str(by)}
        if package:
            params["package"] = package
        return await self._control("/media/seek", params)

    async def key(self, key: str) -> dict[str, Any]:
        """Send a media key, or home/back (app >= 0.29.0)."""
        return await self._control("/key", {"key": key})

    async def volume(
        self,
        level: int | None = None,
        step: str | None = None,
        mute: str | None = None,
    ) -> dict[str, Any]:
        """Set (level 0-100), step (up/down) or mute (on/off/toggle) the volume (app >= 0.29.0)."""
        params: dict[str, str] = {}
        if level is not None:
            params["level"] = str(level)
        elif step is not None:
            params["step"] = step
        elif mute is not None:
            params["mute"] = mute
        return await self._control("/volume", params)

    async def _control(
        self, path: str, params: dict[str, str], timeout: float = 10
    ) -> dict[str, Any]:
        """POST a TV-control call; the app answers JSON with ok + message.

        501 (this device cannot, e.g. a fixed volume) is raised as
        PiPupUnsupportedError, every other failure as PiPupError with the app's message.
        `timeout` is longer for calls the app holds while it waits for a view.
        """
        try:
            async with self._session.post(
                f"{self._base}{path}",
                params=params or None,
                headers=self._headers,
                timeout=aiohttp.ClientTimeout(total=timeout),
            ) as resp:
                text = await resp.text()
                try:
                    body = json.loads(text) if text else {}
                except ValueError:
                    body = {"message": text}
                if not isinstance(body, dict):
                    body = {"message": text}
                if resp.status == 200:
                    return body
                message = body.get("message") or text
                if resp.status == 501:
                    raise PiPupUnsupportedError(message)
                raise PiPupError(f"{path.lstrip('/')} failed ({resp.status}): {message}")
        except PiPupError:
            raise
        except (aiohttp.ClientError, TimeoutError) as err:
            raise PiPupError(f"Cannot reach PiPup at {self._base}: {err}") from err
